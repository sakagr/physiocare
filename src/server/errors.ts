  USERNAME_ALREADY_EXISTS: "USERNAME_ALREADY_EXISTS",
  FORBIDDEN: "FORBIDDEN",
  NOT_FOUND: "NOT_FOUND",
  PATIENT_HAS_DEPENDENT_RECORDS: "PATIENT_HAS_DEPENDENT_RECORDS",
